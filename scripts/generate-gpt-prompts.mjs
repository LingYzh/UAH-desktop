import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Build-time vendoring only: shipped applications never read the documentation tree.
const pack = new URL('../docs/codex-cli-0.157.1-prompts/', import.meta.url);
const modules = {
    GPT_SHARED_TEMPLATE: 'shared-base.md',
    GPT_MAIN_TEMPLATE: 'main-role.md',
    GPT_SUBAGENT_TEMPLATE: 'subagent-role.md',
    GPT_RUNTIME_TEMPLATE: 'runtime-context.md',
};
let output = '// Generated by scripts/generate-gpt-prompts.mjs. Do not edit.\n'
    + '// User-supplied portable adaptation of openai/codex rust-v0.157.1, Apache-2.0.\n'
    + '// Provenance and modifications: docs/CODEX-RUNTIME.md; third-party/codex/NOTICE.\n';
for (const [name, file] of Object.entries(modules)) {
    const bytes = await readFile(new URL(`portable/${file}`, pack));
    output += `\n// ${file} SHA-256: ${createHash('sha256').update(bytes).digest('hex')}\n`;
    output += `export const ${name} = ${JSON.stringify(bytes.toString('utf8'))};\n`;
}
const target = new URL('../src/shared/gpt-prompt-templates.ts', import.meta.url);
if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error('GPT prompt templates differ; run node scripts/generate-gpt-prompts.mjs');
} else await writeFile(target, output, 'utf8');
